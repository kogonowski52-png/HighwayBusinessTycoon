"""Emit the Godot data for an authored frontier plan. Run using Python 3."""
import json
from pathlib import Path
import sys

from frontier_design import DISTRICTS, GATES


ROOT = Path(__file__).resolve().parents[2]
WORK = {
    "fuel": ("attendant","fuel",3.6),
    "rent": ("cashier","cash",5.4), "scooter": ("cashier","cash",4.7),
    "hotel": ("manager","service",6.7), "food": ("server","carry",5.2),
    "retail": ("cashier","cash",5.0), "parking": ("attendant","service",4.9),
    "wash": ("cleaner","clean",5.8), "repair": ("mechanic","repair",6.4),
    "freight": ("attendant","carry",6.9), "cold": ("attendant","carry",7.1),
    "motor": ("cashier","cash",7.0), "ev": ("attendant","service",5.1),
}


def literal(value):
    return json.dumps(value, ensure_ascii=False, separators=(", ", ": "))


def line(points):
    return "[" + ", ".join(f"Vector2({x}, {y})" for x,y in points) + "]"


def write(region):
    d = DISTRICTS[region]
    gate_cash, opening, pace, shortest, quest, manager = d["chapter"]
    sponsor, lead, tier, fuel, rep = GATES[region]
    areas = {"tropical":"#5cae95","route66":"#c17d55","harbor":"#72969f","luxury":"#b9938f","japan":"#a692b6","wilderness":"#92ab9b"}
    coords = {"tropical":(.20,.68),"route66":(.20,.25),"harbor":(.51,.69),"luxury":(.51,.26),"japan":(.81,.68),"wilderness":(.81,.24)}
    title = {"tropical":"Tropical Island","route66":"Route 66","harbor":"Industrial Harbor","luxury":"Luxury City","japan":"Japan Highway","wilderness":"Northern Wilderness"}
    board_x, board_y = coords[region]
    entry = dict(pl=title[region], en=title[region], area=d["map"], color=areas[region], scene=f"res://scenes/world/{region}.tscn",
                 **{"from":sponsor}, cost=gate_cash, fuel=fuel, rep=rep, gate=lead, tier=tier)
    label = {"tropical":("Goście wypożyczalni","Rental customers", "sales_rent", "rent"),
             "route66":("Renowacje Copper Spur","Copper Spur restorations","sales_restoration","restoration"),
             "harbor":("Wymiana kontenerów","Container exchange","deliveries","terminal"),
             "luxury":("Obsługa kolekcjonerów","Collectors' concierge","sales_dealership","dealership"),
             "japan":("Cicha energia","Quiet energy","charged","charge"),
             "wilderness":("Drewno z Timberline","Timberline timber","deliveries","logging")}[region]
    site_schema = []
    art = {}
    prints = {}
    for index, item in enumerate(d["scenes"]):
        key = item["key"]
        role, task, seconds = WORK[item["kind"]]
        kind = item["lane"]
        lane = "truck" if kind=="truck" else "car"
        need = 0 if index==0 else 3 if index < 4 else 4 if index < 7 else 5
        item_cost = max(810,round(item["wage"]*.85))
        site_schema.append([key,item["pl"],item["en"],item["price"],item_cost,seconds,
                            item["cost"],item["gate"],need,item["rep"],item["wage"],item["bays"],kind,role,task,item["kind"]])
        width, length, height = item["size"]
        art[key]=[item["marque"],height-(.31 if item["kind"] in ("fuel","parking","ev") else .18), length*.53+.13,height+.76]
        x, z = item["at"]
        prints[key]=f'[Vector2({x}, {z}), "{lane}", {item["spacing"]}, {item["setback"]}, {len(item["bays"])}]'
    coords_text = ", ".join(str(x) for x in d["center"])
    layout = [
        f'\t"family": "{region}", "center": Vector3({coords_text}), "width": 38.0, "ambient": {d["ambient"]},',
        f'\t"car": {line(d["road"])}, "queue": {d["queue"]},',
    ]
    if "truck" in d:
        layout.append(f'\t"truck": {line(d["truck"])}, "truck_queue": {d["truck_queue"]},')
    if "look" in d:
        layout.append(f'\t"look": {d["look"]},')
    if d.get("boulevard"):
        layout.append('\t"boulevard": true,')
    layout.append('\t"plots": {')
    for key,value in prints.items():
        layout.append(f'\t\t"{key}": {value},')
    layout += ['\t},', f'\t"fleet": {literal(d["fleet"])}, "guests": {literal(d["guests"])},',
               f'\t"weights": {literal(d["weights"])}, "specialties": {literal(d["specialties"])},',
               f'\t"palette": {literal(["#"+code for code in d["surface"]])}, "frontier": true,']
    pilot_models = [vehicle for vehicle in d["fleet"] if vehicle not in ("cove", "sundown", "ridgeback")][:3]
    out = [
        "extends RefCounted",
        "",
        "# Generated by tools/art/frontier_data.py from the authored district plan.",
        f'const ATLAS := {literal(entry)[:-1]}, "position": Vector2({board_x}, {board_y})}}',
        f"const STAMPS := {literal(pilot_models)}",
        "const LAYOUT := {",
        *layout,
        "}",
        "const SERVICES := [",
        *["\t"+literal(x)+"," for x in site_schema],
        "]",
        f'const ECONOMICS := {literal([opening, pace, shortest, 109, 109, quest, manager])}',
        'const CONTRACT := '+literal(dict(field=label[2], site=label[3], count=12, time=1800,
                                           cash=round(opening*.72),pl=label[0],en=label[1])),
        "const SIGNS := {",
        *[f'\t"{key}": {literal(x)},' for key,x in art.items()],
        "}",
        "",
    ]
    filename = ROOT / "data/world/frontier" / (region+".gd")
    filename.parent.mkdir(exist_ok=True)
    filename.write_text("\n".join(out))
    scene = ROOT / entry["scene"].removeprefix("res://")
    scene.write_text('[gd_scene load_steps=2 format=3]\n\n[ext_resource type="Script" path="res://scripts/core/game_manager.gd" id="1"]\n\n[node name="'+d["map"].replace(" ","")+'" type="Node3D"]\nscript = ExtResource("1")\n')


if __name__ == "__main__":
    for region in sys.argv[1:] or DISTRICTS:
        write(region)
